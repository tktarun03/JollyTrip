#!/usr/bin/env python3
"""Builds JollyTrip from src/.

  python3 build.py                   index.html (served by GitHub Pages), docs/CODEMAP.md and CHANGELOG.md
  python3 build.py --preview FILE    also writes a body-only copy for a claude.ai preview artifact

Only the standard library is used. The output is deterministic, so CI can check that the committed
files match src/ (a plain `git diff --exit-code` after building).
"""
import os, re, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, 'src')
# Order matters: later files use helpers from earlier ones, and z-start.js boots the app.
JS = ['a-core.js', 'b-data.js', 'c-views.js', 'd-sheets.js', 'e-events.js', 'f-extra.js',
      'g-wallet.js', 'h-maps.js', 'i-backup-cal.js', 'z-start.js']
LIBS = [('lib-cookie.js', 'js-cookie 3.0.5, MIT'), ('lib-lz.js', 'lz-string 1.5.0, MIT'),
        ('lib-qr.js', 'qrcode-generator 1.4.4, MIT, Kazuhiko Arase')]
PREVIEW_META = '<meta name="claude:viewport-fit-sides" content="cover">\n'


def r(n):
    return open(os.path.join(SRC, n), encoding='utf-8').read()


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def build_app():
    js = "(function () {\n  'use strict';\n" + ''.join(r(n) for n in JS) + "})();\n"
    libs = ''.join('<script>/* %s */\n%s\n</script>\n' % (note, r(f).strip()) for f, note in LIBS)
    style = '<style>\n' + r('style.css') + '</style>\n'
    page = ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">\n'
            '<meta name="theme-color" content="#F4F6F5">\n<meta name="apple-mobile-web-app-capable" content="yes">\n'
            '<meta name="mobile-web-app-capable" content="yes">\n<meta name="apple-mobile-web-app-title" content="JollyTrip">\n'
            '<meta name="description" content="JollyTrip: family trip planner, itinerary, bookings, packing list and holiday budget tracker.">\n'
            '<link rel="manifest" href="manifest.webmanifest">\n<link rel="icon" type="image/png" sizes="192x192" href="icons/icon-192.png">\n'
            '<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">\n' + r('head.html').replace(PREVIEW_META, '') +
            '<style>:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>\n'
            + style + '</head>\n<body>\n' + r('body.html') + libs + '<script>\n' + js + '</script>\n</body>\n</html>\n')
    preview = r('head.html') + style + r('body.html') + libs + '<script>\n' + js + '</script>\n'
    return page, preview


# ---------- docs/CODEMAP.md: where everything is, so nobody has to read whole files ----------
FUNC = re.compile(r'^  (?:async )?function ([A-Za-z_$][\w$]*)\s*\(([^)]*)\)')
VAR = re.compile(r'^  var ([A-Z][A-Z0-9_]+)\s*=')
KEY = re.compile(r"^\s{4}'?([\w-]+)'?\s*:\s*(?:function|[A-Za-z_$][\w$]*\s*,?\s*$)")
SECTION = re.compile(r'^\s*/\*\s*=+\s*$')


def codemap():
    out = ['# Code map', '',
           'Generated by `python3 build.py`. Do not edit by hand.', '',
           'Every top-level function, constant, button action (`ACT`) and bottom sheet (`SHEETS`) in `src/`, '
           'with its line number. Find what you need here, then read only those lines '
           '(for example `sed -n 120,160p src/c-views.js`).', '']
    for name in JS:
        lines = r(name).split('\n')
        funcs, consts, acts, sections = [], [], [], []
        in_act = False
        for i, line in enumerate(lines, 1):
            if SECTION.match(line) and i < len(lines) and lines[i].strip():
                sections.append((i, lines[i].strip()))
            m = FUNC.match(line)
            if m:
                funcs.append((i, m.group(1), m.group(2).replace(' ', '')))
            m = VAR.match(line)
            if m:
                consts.append((i, m.group(1)))
            if re.search(r'(var ACT = \{|Object\.assign\(ACT, \{)', line):
                in_act = True
                continue
            if in_act:
                if re.match(r'^  \}\)?;', line):
                    in_act = False
                else:
                    m = KEY.match(line)
                    if m:
                        acts.append((i, m.group(1)))
        size = os.path.getsize(os.path.join(SRC, name))
        out.append('## `%s`  (%d lines, %d KB)' % (name, len(lines), round(size / 1024)))
        out.append('')
        if sections:
            out.append('Sections: ' + ' · '.join('%s (L%d)' % (t, i) for i, t in sections))
            out.append('')
        if consts:
            out.append('Constants: ' + ', '.join('`%s` L%d' % (n, i) for i, n in consts))
            out.append('')
        if funcs:
            out.append('Functions: ' + ', '.join('`%s(%s)` L%d' % (n, a, i) for i, n, a in funcs))
            out.append('')
        if acts:
            out.append('Actions (`data-act`): ' + ', '.join('`%s` L%d' % (n, i) for i, n in acts))
            out.append('')
    sheets = []
    for name in JS:
        for m in re.finditer(r"(?:var SHEETS = \{|Object\.assign\(SHEETS, \{)([^}]*)\}", r(name)):
            for k, v in re.findall(r'([\w-]+)\s*:\s*(\w+)', m.group(1)):
                sheets.append('`%s` → `%s` (%s)' % (k, v, name))
    if sheets:
        out += ['## Bottom sheets (`openSheet({ type })`)', '', ', '.join(sheets), '']
    return '\n'.join(out)


# ---------- CHANGELOG.md, from the in-app CHANGELOG array (one source of truth) ----------
def changelog():
    src = r('b-data.js')
    start = src.index('var CHANGELOG = [')
    block = src[start:src.index('\n  ];', start)]
    out = ['# Changelog', '', 'Generated by `python3 build.py` from `CHANGELOG` in `src/b-data.js`, '
           'which is also what the app shows under More → What’s new. Edit it there.', '']
    for v, date, items in re.findall(r"\{ v: '([^']+)', date: '([^']+)', items: \[(.*?)\] \}", block):
        out.append('## %s · %s' % (v, date))
        out.append('')
        for it in re.findall(r"'((?:[^'\\]|\\.)*)'", items):
            out.append('- ' + it.replace("\\'", "'"))
        out.append('')
    return '\n'.join(out)


if __name__ == '__main__':
    page, preview = build_app()
    write('index.html', page)
    write('docs/CODEMAP.md', codemap())
    write('CHANGELOG.md', changelog())
    print('Built index.html (%d bytes), docs/CODEMAP.md, CHANGELOG.md' % len(page))
    if '--preview' in sys.argv:
        dest = sys.argv[sys.argv.index('--preview') + 1]
        with open(dest, 'w', encoding='utf-8') as f:
            f.write(preview)
        print('Preview written to', dest)
